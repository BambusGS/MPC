function assertKalmanModelP6(model)
    modelName = string(model.name);
    n = size(model.A, 1);
    ny = size(model.C, 1);
    nw = size(model.G, 2);

    assert(isequal(size(model.A), [n, n]) && size(model.B, 1) == n && size(model.G, 1) == n, ...
        modelName + " state/input/noise matrix dimensions are inconsistent.");
    assert(isequal(size(model.C), [ny, n]) && isequal(size(model.Q), [nw, nw]) && ...
        isequal(size(model.R), [ny, ny]) && isequal(size(model.S), [nw, ny]) && ...
        isequal(size(model.P0), [n, n]), modelName + " KF covariance dimensions are inconsistent.");
    assert(all(isfinite(model.A(:))) && all(isfinite(model.B(:))) && ...
        all(isfinite(model.G(:))) && all(isfinite(model.C(:))) && ...
        all(isfinite(model.R(:))) && all(isfinite(model.S(:))) && ...
        all(isfinite(model.P0(:))), modelName + " must contain finite matrices.");
    assertCovarianceP6(model.Q, modelName + " process covariance");
end
